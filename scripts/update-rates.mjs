#!/usr/bin/env node
// Refreshes the currency rates that ship inside the app (packages/core/src/currency-rates.ts) from the European Central
// Bank's own Data Portal (the euro foreign exchange reference rates, the latest day for every currency) and from the
// central banks the app reads for currencies the ECB doesn't quote: the National Bank of Ukraine (UAH) and the Central
// Bank of Argentina (ARS). The app uses these until it downloads newer ones itself (and always with no internet), so
// run this before a release:
//   node scripts/update-rates.mjs
// Only those official sources are asked (no key, no identifiers); the same addresses and checks as the app
// (packages/core/src/currency.ts, central-banks.ts). The dollar pegs and the CFA franc parity are fixed in the app itself.
import { writeFileSync } from "node:fs";

const URL_ = "https://data-api.ecb.europa.eu/service/data/EXR/D..EUR.SP00.A?lastNObservations=1&format=csvdata&detail=dataonly";
const OUT = new URL("../packages/core/src/currency-rates.ts", import.meta.url);

const res = await fetch(URL_, { headers: { Accept: "text/csv" } });
if (!res.ok) throw new Error(`ECB answered ${res.status}`);
const lines = (await res.text()).trim().split(/\r?\n/).map((l) => l.split(","));
const head = lines.shift() ?? [];
const col = (n) => { const i = head.indexOf(n); if (i < 0) throw new Error(`ECB data: no ${n} column`); return i; };
const C = col("CURRENCY"), D = col("TIME_PERIOD"), V = col("OBS_VALUE");
// per currency its newest row (the newest day can lack some); rows more than 30 days older than the newest day are
// dropped (RUB, ARS, ... still answer with their last, years-old rate). Same rule as parseEcbCsv in the app.
const own = {};
for (const r of lines) if (/^[A-Z]{3}$/.test(r[C]) && /^\d+(\.\d+)?$/.test(r[V]) && Number(r[V]) > 0 && r[D] >= (own[r[C]]?.[0] ?? "")) own[r[C]] = [r[D], r[V]];
const date = Object.values(own).reduce((m, [d]) => (d > m ? d : m), "");
const day = (d) => Date.parse(d + "T12:00:00Z") / 86_400_000;
const kept = Object.entries(own).filter(([, [d]]) => day(date) - day(d) <= 30).sort(([a], [b]) => a.localeCompare(b));
const rates = Object.fromEntries(kept.map(([c, [, v]]) => [c, v]));
const dates = Object.fromEntries(kept.filter(([, [d]]) => d !== date).map(([c, [d]]) => [c, d]));
if (!/^\d{4}-\d\d-\d\d$/.test(date) || Object.keys(rates).length < 20) throw new Error("ECB data looks incomplete");

// the central banks: each its own currency's rate of the euro and its day (same checks as parseNbuJson / parseBcraJson)
const dec = (n) => (typeof n === "number" && Number.isFinite(n) && n > 0 && /^\d+(\.\d+)?$/.test(String(n)) ? String(n) : null);
const isDay = (d) => {
  if (!/^\d{4}-\d\d-\d\d$/.test(d)) return false;
  const [y, m, day] = d.split("-").map(Number), t = new Date(Date.UTC(y, m - 1, day));
  return t.getUTCFullYear() === y && t.getUTCMonth() === m - 1 && t.getUTCDate() === day;
};
const json = async (u) => { const r = await fetch(u, { headers: { Accept: "application/json" } }); if (!r.ok) throw new Error(`${u} answered ${r.status}`); return r.json(); };
const sources = {};
const nbuEur = (await json("https://bank.gov.ua/NBUStatService/v1/statdirectory/exchange?json")).find((x) => x?.cc === "EUR");
const nbuDay = /^(\d\d)\.(\d\d)\.(\d{4})$/.exec(nbuEur?.exchangedate ?? "");
const nbu = [nbuDay ? `${nbuDay[3]}-${nbuDay[2]}-${nbuDay[1]}` : "", nbuEur?.r030 === 978 ? dec(nbuEur.rate) : null];
const bcraRes = (await json("https://api.bcra.gob.ar/estadisticascambiarias/v1.0/Cotizaciones")).results;
const bcra = [bcraRes?.fecha ?? "", dec(bcraRes?.detalle?.find((x) => x?.codigoMoneda === "EUR")?.tipoCotizacion)];
for (const [code, src, [d, v]] of [["UAH", "nbu", nbu], ["ARS", "bcra", bcra]]) {
  if (!isDay(d) || !v) throw new Error(`${src} data looks incomplete`);
  rates[code] = v; sources[code] = src; if (d !== date) dates[code] = d;
}
// the newest day of all of them is the set's day; the others keep their own
const newest = Object.entries(rates).map(([c]) => dates[c] ?? date).reduce((m, d) => (d > m ? d : m), date);
if (newest !== date) for (const c of Object.keys(rates)) { const d = dates[c] ?? date; if (d === newest) delete dates[c]; else dates[c] = d; }
const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));

const block = (name, o) => (Object.keys(o).length ? `\n  ${name}: {\n${Object.entries(sorted(o)).map(([k, v]) => `    ${k}: "${v}",`).join("\n")}\n  },` : "");
writeFileSync(OUT, `// The official euro rates that ship with the app (1 EUR = rate units of each currency), so the converter works with
// no internet from the first open: the ECB's reference rates, plus the central banks' own (sources: nbu = National Bank
// of Ukraine, bcra = Central Bank of Argentina). Generated by scripts/update-rates.mjs; don't edit.
export const BUNDLED_RATES: { date: string; rates: Record<string, string>; dates?: Record<string, string>; sources?: Record<string, string> } = {
  date: "${newest}",
  rates: {
${Object.entries(sorted(rates)).map(([k, v]) => `    ${k}: "${v}",`).join("\n")}
  },${block("dates", dates)}${block("sources", sources)}
};
`);
console.log(`Official rates of ${newest}: ${Object.keys(rates).length} currencies (ECB ${date}, NBU ${nbu[0]}, BCRA ${bcra[0]}) written to ${OUT.pathname}`);
