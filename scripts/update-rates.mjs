#!/usr/bin/env node
// Refreshes the currency rates that ship inside the app (packages/core/src/currency-rates.ts) from the European Central
// Bank's own Data Portal: the euro foreign exchange reference rates, the latest day for every currency. The app uses
// these until it downloads newer ones itself (and always with no internet), so run this before a release:
//   node scripts/update-rates.mjs
// Only the ECB is asked (no key, no identifiers); the same address and parsing as the app (packages/core/src/currency.ts).
import { writeFileSync } from "node:fs";

const URL_ = "https://data-api.ecb.europa.eu/service/data/EXR/D..EUR.SP00.A?lastNObservations=1&format=csvdata&detail=dataonly";
const OUT = new URL("../packages/core/src/currency-rates.ts", import.meta.url);

const res = await fetch(URL_, { headers: { Accept: "text/csv" } });
if (!res.ok) throw new Error(`ECB answered ${res.status}`);
const lines = (await res.text()).trim().split(/\r?\n/).map((l) => l.split(","));
const head = lines.shift() ?? [];
const col = (n) => { const i = head.indexOf(n); if (i < 0) throw new Error(`ECB data: no ${n} column`); return i; };
const C = col("CURRENCY"), D = col("TIME_PERIOD"), V = col("OBS_VALUE");
// the series of currencies the ECB no longer quotes (RUB, ARS, ...) still answer with their last, years-old rate:
// only the latest day's rates are kept
const date = lines.reduce((m, r) => (r[D] > m ? r[D] : m), "");
const rates = Object.fromEntries(lines.filter((r) => r[D] === date && /^\d+(\.\d+)?$/.test(r[V]) && Number(r[V]) > 0).map((r) => [r[C], r[V]]).sort());
if (!/^\d{4}-\d\d-\d\d$/.test(date) || Object.keys(rates).length < 20) throw new Error("ECB data looks incomplete");

writeFileSync(OUT, `// The ECB's euro reference rates that ship with the app (1 EUR = rate units of each currency), so the converter works
// with no internet from the first open. Generated by scripts/update-rates.mjs from the ECB Data Portal; don't edit.
export const BUNDLED_RATES: { date: string; rates: Record<string, string> } = {
  date: "${date}",
  rates: {
${Object.entries(rates).map(([k, v]) => `    ${k}: "${v}",`).join("\n")}
  },
};
`);
console.log(`ECB reference rates of ${date}: ${Object.keys(rates).length} currencies written to ${OUT.pathname}`);
